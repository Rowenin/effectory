/**
 * Generates the table of modules the Effectory host provides to application
 * and extension code. Each specifier maps to a lazy `require` so a compiled
 * binary includes every module statically but evaluates only what is imported.
 *
 *   bun scripts/generate-host-modules.ts          # write
 *   bun scripts/generate-host-modules.ts --check  # fail when stale
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { Schema } from "effect";

const root = path.resolve(import.meta.dir, "..");
const output = path.join(
  root,
  "packages/platform-bun/src/host-modules.generated.ts"
);

function packageRoot(name: string) {
  return path.dirname(
    fileURLToPath(import.meta.resolve(`${name}/package.json`))
  );
}

/** Every public `effect` entry: named exports plus files matched by `./*`. */
function effectSpecifiers() {
  const directory = packageRoot("effect");
  const manifest = Schema.decodeSync(
    Schema.fromJsonString(
      Schema.Struct({
        exports: Schema.Record(Schema.String, Schema.Unknown),
        version: Schema.String,
      })
    )
  )(readFileSync(path.join(directory, "package.json"), "utf-8"));
  const specifiers = new Set<string>();
  for (const [key, target] of Object.entries(manifest.exports)) {
    if (target !== null && !key.includes("*") && key !== "./package.json") {
      specifiers.add(key === "." ? "effect" : `effect/${key.slice(2)}`);
    }
  }
  const dist = path.join(directory, "dist");
  const walk = (relative: string): void => {
    for (const entry of readdirSync(path.join(dist, relative), {
      withFileTypes: true,
    })) {
      const next = relative === "" ? entry.name : `${relative}/${entry.name}`;
      if (entry.isDirectory()) {
        // Internal modules are not part of Effect's public surface.
        if (entry.name !== "internal") {
          walk(next);
        }
      } else if (entry.name.endsWith(".js") && entry.name !== "index.js") {
        specifiers.add(`effect/${next.slice(0, -3)}`);
      }
    }
  };
  walk("");
  return { specifiers, version: manifest.version };
}

function coreSpecifiers() {
  const manifest = Schema.decodeSync(
    Schema.fromJsonString(
      Schema.Struct({ exports: Schema.Record(Schema.String, Schema.String) })
    )
  )(readFileSync(path.join(root, "packages/core/package.json"), "utf-8"));
  return Object.keys(manifest.exports)
    .filter((key) => key !== "./package.json")
    .map((key) =>
      key === "."
        ? "@offtree/effectory-sdk"
        : `@offtree/effectory-sdk/${key.slice(2)}`
    );
}

const effect = effectSpecifiers();
const specifiers = [...effect.specifiers, ...coreSpecifiers()].toSorted();
const source = `// Generated by scripts/generate-host-modules.ts. Do not edit.
/* oxlint-disable */
// Lazy requires keep every module in a compiled binary while evaluating only
// what application or extension code imports.

export const effectVersion = ${JSON.stringify(effect.version)};

export const hostModuleLoaders: Readonly<Record<string, () => object>> = {
${specifiers
  .map(
    (specifier) =>
      `  ${JSON.stringify(specifier)}: () => require(${JSON.stringify(specifier)}),`
  )
  .join("\n")}
};
`;

if (process.argv.includes("--check")) {
  if (readFileSync(output, "utf-8") !== source) {
    console.error(
      "host-modules.generated.ts is stale; run bun scripts/generate-host-modules.ts"
    );
    process.exit(1);
  }
} else {
  writeFileSync(output, source);
  console.log(
    `${specifiers.length} host modules -> ${path.relative(root, output)}`
  );
}
