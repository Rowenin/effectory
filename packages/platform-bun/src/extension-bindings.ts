import {
  existsSync,
  readFileSync,
  lstatSync,
  mkdirSync,
  writeFileSync,
  openSync,
  fsyncSync,
  closeSync,
  renameSync,
  rmSync,
} from "node:fs";
import path from "node:path";

import type { ExtensionLock } from "@effectory/runtime/extension-protocol";
import { Digest, extensionLimits } from "@effectory/runtime/extension-protocol";
import { OperationError } from "@effectory/runtime/protocol";
import { Schema } from "effect";

import {
  emptyLock,
  lockRevision,
  packagePath,
  validateLock,
} from "./extension-cache.ts";
import { readStoredLockContents } from "./runtime-storage-format.ts";

export const lockFilename = (repository: string) =>
  path.join(repository, "effectory.extensions.lock.json");
export const bindingsFilename = (repository: string) =>
  path.join(repository, "effectory.extensions.ts");
const trustFilename = (repository: string) =>
  path.join(repository, ".effectory", "extensions", "trust.json");
const Trust = Schema.Struct({
  digests: Schema.Array(Digest).check(Schema.isMaxLength(4096)),
  format: Schema.Literal(1),
});
const invalid = (message: string) =>
  new OperationError({ code: "InvalidInput", message });

function readJson(filename: string, maximum: number): unknown {
  const stat = lstatSync(filename);
  if (!stat.isFile() || stat.isSymbolicLink() || stat.size > maximum) {
    throw invalid("Extension metadata must be a bounded regular file");
  }
  try {
    return JSON.parse(readFileSync(filename, "utf-8"));
  } catch {
    throw invalid("Extension metadata contains invalid JSON");
  }
}
export function readLock(repository: string) {
  const contents = readStoredLockContents(repository);
  return contents === null ? emptyLock : validateLock(JSON.parse(contents));
}

/** Complete-file replacement; callers hold the repository mutation lease. */
export function replaceFile(filename: string, contents: string) {
  mkdirSync(path.dirname(filename), { mode: 0o700, recursive: true });
  const staging = `${filename}.${crypto.randomUUID()}.tmp`;
  try {
    writeFileSync(staging, contents, { flag: "wx", mode: 0o600 });
    const file = openSync(staging, "r");
    try {
      fsyncSync(file);
    } finally {
      closeSync(file);
    }
    renameSync(staging, filename);
    const directory = openSync(path.dirname(filename), "r");
    try {
      fsyncSync(directory);
    } finally {
      closeSync(directory);
    }
  } finally {
    rmSync(staging, { force: true });
  }
}

export function bindingSource(
  repository: string,
  snapshot: typeof ExtensionLock.Type
): string {
  const lock = validateLock(snapshot);
  const entries = Object.entries(lock.roots)
    .filter(([, root]) => root.bindingName !== undefined)
    .toSorted(([left], [right]) => {
      if (left === right) {
        return 0;
      }
      return left < right ? -1 : 1;
    });
  const header = `// Generated by Effectory. Restore from effectory.extensions.lock.json.\n// Lock revision: ${lockRevision(lock)}\n`;
  if (entries.length === 0) {
    return `${header}export {};\n`;
  }
  const identifiers = new Set(entries.map(([, root]) => root.bindingName));
  let counter = 0;
  const fresh = () => {
    let name: string;
    do {
      name = `$effectory${counter}`;
      counter += 1;
    } while (identifiers.has(name));
    identifiers.add(name);
    return name;
  };
  const sdk = fresh();
  const lines = [
    header,
    `import { Extension as ${sdk} } from "@offtree/effectory-sdk";`,
  ];
  for (const [id, root] of entries) {
    const locked = lock.packages[id];
    if (!locked || root.bindingName === undefined) {
      throw invalid("Binding package is missing from the lock");
    }
    const contract = fresh();
    const moduleName = fresh();
    const relative = (filename: string) =>
      `./${path
        .relative(
          repository,
          path.join(packagePath(repository, locked), filename)
        )
        .split(path.sep)
        .join("/")}`;
    lines.push(
      `import { ${locked.manifest.contracts.export} as ${contract} } from ${JSON.stringify(relative(locked.manifest.contracts.file))};`,
      `export const ${root.bindingName} = ${sdk}.installed(`,
      `  ${contract},`,
      `  async () => {`,
      `    const ${moduleName} = await import(${JSON.stringify(relative(locked.manifest.entrypoint.file))});`,
      `    return ${moduleName}[${JSON.stringify(locked.manifest.entrypoint.export)}];`,
      `  },`,
      `  ${JSON.stringify(locked.archiveDigest)}`,
      `);`
    );
  }
  const source = `${lines.join("\n")}\n`;
  if (Buffer.byteLength(source) > extensionLimits.manifestBytes) {
    throw invalid("Generated extension bindings exceed 256 KiB");
  }
  return source;
}
export function assertWritableBindings(repository: string) {
  const filename = bindingsFilename(repository);
  if (
    existsSync(filename) &&
    (!lstatSync(filename).isFile() ||
      lstatSync(filename).isSymbolicLink() ||
      lstatSync(filename).size > extensionLimits.manifestBytes ||
      !readFileSync(filename, "utf-8").startsWith("// Generated by Effectory."))
  ) {
    throw new OperationError({
      code: "Conflict",
      message: "Refusing to replace a handwritten effectory.extensions.ts",
    });
  }
}
export function writeBindings(
  repository: string,
  lock: typeof ExtensionLock.Type
) {
  assertWritableBindings(repository);
  const source = bindingSource(repository, lock);
  replaceFile(bindingsFilename(repository), source);
  return lockRevision(lock);
}
export function verifyBindings(
  repository: string,
  lock: typeof ExtensionLock.Type
) {
  const expected = bindingSource(repository, lock);
  const filename = bindingsFilename(repository);
  if (
    !existsSync(filename) ||
    lstatSync(filename).isSymbolicLink() ||
    lstatSync(filename).size !== Buffer.byteLength(expected) ||
    readFileSync(filename, "utf-8") !== expected
  ) {
    throw invalid(
      "Extension bindings are missing or stale; run effectory extension restore"
    );
  }
}
function readTrust(repository: string): Set<string> {
  const filename = trustFilename(repository);
  if (!existsSync(filename)) {
    return new Set();
  }
  try {
    return new Set(
      Schema.decodeUnknownSync(Trust)(readJson(filename, 524_288), {
        onExcessProperty: "error",
      }).digests
    );
  } catch {
    throw invalid("Local extension trust metadata is invalid");
  }
}

/** Retained application bundles require their original trust decisions too. */
export function assertTrustedDigests(
  repository: string,
  digests: readonly string[]
) {
  const trusted = readTrust(repository);
  if (digests.some((digest) => !trusted.has(digest))) {
    throw new OperationError({
      code: "Unauthorized",
      message:
        "A retained application requires extension digests that have not been trusted on this machine",
    });
  }
}

/** Only call for an explicit trust decision for this exact lock snapshot. */
export function trustLock(
  repository: string,
  snapshot: typeof ExtensionLock.Type
) {
  const lock = validateLock(snapshot);
  const trusted = readTrust(repository);
  for (const locked of Object.values(lock.packages)) {
    trusted.add(locked.archiveDigest);
  }
  if (trusted.size > 4096) {
    throw invalid("Local extension trust history exceeds 4096 digests");
  }
  replaceFile(
    trustFilename(repository),
    JSON.stringify({ digests: [...trusted].toSorted(), format: 1 })
  );
}

/** Tracked lockfiles never grant permission to execute downloaded code. */
export function assertTrusted(
  repository: string,
  lock: typeof ExtensionLock.Type
) {
  const trusted = readTrust(repository);
  for (const locked of Object.values(lock.packages)) {
    if (!trusted.has(locked.archiveDigest)) {
      throw new OperationError({
        code: "Unauthorized",
        message: `Extension ${locked.manifest.id}@${locked.manifest.version} has not been trusted on this machine. Review its capabilities and use extension restore --trust.`,
      });
    }
  }
}
